// Run with PLAYWRIGHT_MODULE pointing to an installed Playwright package.
require('dotenv').config();
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const path = require('node:path');
const os = require('node:os');
const jwt = require('jsonwebtoken');
const { pool } = require('../src/config/db');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const seed = require('./data/destinations.seed.json');
const origin = 'http://127.0.0.1:5173';
const api = 'http://127.0.0.1:5001/api';
async function run() {
  const { rows } = await pool.query("SELECT id FROM admins WHERE status='active' AND role_key='owner' AND must_change_password=0 LIMIT 1");
  const token = jwt.sign({ sub: rows[0].id, jti: randomUUID(), type: 'admin' }, process.env.JWT_ADMIN_SECRET || 'dev_admin_secret', { expiresIn: '10m' });
  await pool.end();
  const request = async (route, method = 'GET', body) => {
    const response = await fetch(api + route, { method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const result = await response.json();
    assert.ok(response.ok, result.message);
    return result.data;
  };
  const browser = await chromium.launch({ headless: true });
  let temporary;
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin, { waitUntil: 'domcontentloaded' });
    const section = page.locator('.island-discovery');
    await section.waitFor({ timeout: 60000 });
    await section.scrollIntoViewIfNeeded();
    const headings = await page.locator('h2').allTextContents();
    assert.equal(headings.indexOf('Islands and Famous Views in Seychelles'), headings.indexOf('Featured Stays in Seychelles') + 1);
    assert.equal(headings.indexOf('Top Excursions & Activities'), headings.indexOf('Islands and Famous Views in Seychelles') + 1);
    const viewport = page.locator('.island-viewport');
    const position = () => viewport.evaluate(el => el.scrollLeft);
    await page.waitForTimeout(300);
    let before = await position();
    await page.waitForTimeout(1200);
    const automatic = (await position()) - before;
    assert.ok(automatic >= 10 && automatic <= 30, `Slow movement: ${automatic}px`);
    await viewport.hover();
    before = await position();
    await page.waitForTimeout(600);
    assert.equal(await position(), before, 'Hover must pause movement.');
    const rect = await viewport.boundingBox();
    await page.mouse.move(rect.x + 500, rect.y + 70);
    await page.mouse.down();
    await page.mouse.move(rect.x + 350, rect.y + 70, { steps: 12 });
    await page.mouse.up();
    assert.ok((await position()) - before >= 140, 'Mouse dragging must move the carousel.');
    assert.equal(new URL(page.url()).pathname, '/', 'Dragging must not follow the card link.');
    const groupWidth = await page.locator('.island-track-group').first().evaluate(el => el.getBoundingClientRect().width);
    await viewport.evaluate((el, width) => { el.scrollLeft = width; }, groupWidth);
    await viewport.hover();
    await section.screenshot({ path: path.join(os.tmpdir(), 'islands-section.png') });
    const links = page.locator('.island-track-group').nth(1).locator('a');
    await links.nth(1).click();
    await page.getByRole('heading', { level: 1, name: seed[1].name }).waitFor({ timeout: 60000 });
    await page.getByRole('button', { name: /^View .* photo 1$/ }).click();
    const dialog = page.getByRole('dialog', { name: 'Destination photo viewer' });
    await dialog.waitFor();
    await page.keyboard.press('ArrowRight');
    await page.getByText('2 / 6', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await dialog.count(), 0);
    assert.ok(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')?.startsWith('View ')), 'Lightbox restores focus.');
    await page.locator('summary').first().click();
    assert.equal(await page.locator('details').first().getAttribute('open'), '');
    await page.screenshot({ path: path.join(os.tmpdir(), 'islands-detail.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: placement, slow autoplay, hover pause, mouse drag, card navigation, lightbox arrows/Escape/focus and FAQs.');

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await mobile.goto(origin, { waitUntil: 'domcontentloaded' });
    await mobile.locator('.island-discovery').waitFor({ timeout: 60000 });
    await mobile.locator('.island-discovery').scrollIntoViewIfNeeded();
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Homepage must not overflow on mobile.');
    const mobileViewport = mobile.locator('.island-viewport');
    const bounds = await mobileViewport.boundingBox();
    const client = await mobile.context().newCDPSession(mobile);
    before = await mobileViewport.evaluate(el => el.scrollLeft);
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x + 260, y: bounds.y + 80 }] });
    for (let step = 1; step <= 10; step++) await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: bounds.x + 260 - step * 14, y: bounds.y + 80 }] });
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.ok((await mobileViewport.evaluate(el => el.scrollLeft)) - before >= 120, 'Touch dragging must move cards.');
    await mobile.screenshot({ path: path.join(os.tmpdir(), 'islands-mobile.png') });
    await mobile.emulateMedia({ reducedMotion: 'reduce' });
    await mobile.waitForTimeout(100);
    before = await mobileViewport.evaluate(el => el.scrollLeft);
    await mobile.waitForTimeout(600);
    assert.equal(await mobileViewport.evaluate(el => el.scrollLeft), before, 'Reduced motion disables autoplay.');
    await mobile.goto(origin + '/islands/mahe');
    await mobile.getByRole('heading', { level: 1, name: seed[0].name }).waitFor({ timeout: 60000 });
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Detail page must not overflow on mobile.');
    console.log('PASS: mobile layout, touch drag and reduced-motion preference.');

    temporary = (await request('/admin/website/destinations', 'POST', { ...seed[0], slug: `browser-check-${randomUUID()}`, name: 'Temporary browser check', published: false })).destination;
    const admin = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await admin.addInitScript(value => {
      localStorage.setItem('adminToken', value);
      localStorage.setItem('adminData', JSON.stringify({ token: value }));
    }, token);
    await admin.goto(origin + '/admin/dashboard/website-home?tab=islands');
    await admin.getByRole('heading', { name: 'Island Configuration', exact: true }).waitFor({ timeout: 60000 });
    await admin.getByRole('button', { name: /Temporary browser check/ }).click();
    await admin.getByLabel('Short description', { exact: false }).fill('Temporary browser editing verification.');
    await admin.getByRole('button', { name: 'Save destination', exact: true }).click();
    await admin.getByText('Draft saved. It is not visible on the website.', { exact: true }).waitFor({ timeout: 30000 });
    let saved = (await request('/admin/website/destinations')).items.find(item => item.id === temporary.id);
    assert.equal(saved.shortDescription, 'Temporary browser editing verification.');
    await admin.getByLabel('Published', { exact: true }).check();
    await admin.getByRole('button', { name: 'Save destination', exact: true }).click();
    await admin.getByText('Destination saved and published.', { exact: true }).waitFor({ timeout: 30000 });
    assert.equal((await request(`/destinations/${temporary.slug}`)).destination.shortDescription, saved.shortDescription);
    await admin.getByRole('button', { name: /Mah.* Island.*Published/ }).click();
    await admin.screenshot({ path: path.join(os.tmpdir(), 'islands-admin.png') });
    console.log('PASS: admin tab, editable form, database persistence and publication from the UI.');
  } finally {
    if (temporary) await request(`/admin/website/destinations/${temporary.id}`, 'DELETE');
    await browser.close();
  }
}
run().catch(error => { console.error(error.stack); pool.end().catch(() => {}); process.exitCode = 1; });
